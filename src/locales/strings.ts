export function toArabicIndic(num: number | string): string {
  const indicDigits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(num).replace(/[0-9]/g, (w) => indicDigits[parseInt(w, 10)]);
}

export function t(
  locale: AppLocale,
  key: string,
  placeholders?: Record<string, string | number>,
  useIndicNumerals?: boolean
): string {
  const dict = translations[locale] || translations.en;
  let str = dict[key] || translations.en[key] || key;
  if (placeholders) {
    for (const [k, v] of Object.entries(placeholders)) {
      const valStr = useIndicNumerals && locale === 'ar' ? toArabicIndic(v) : String(v);
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), valStr);
    }
  }
  return str;
}
