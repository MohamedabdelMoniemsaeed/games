@immutable
class FarmPalette extends ThemeExtension<FarmPalette> {
  const FarmPalette({
    required this.cream,
    required this.green,
    required this.dark,
    required this.muted,
    required this.paleGreen,
    required this.orange,
    required this.blue,
    required this.border,
  });

  final Color cream;
  final Color green;
  final Color dark;
  final Color muted;
  final Color paleGreen;
  final Color orange;
  final Color blue;
  final Color border;

  @override
  FarmPalette copyWith({
    Color? cream,
    Color? green,
    Color? dark,
    Color? muted,
    Color? paleGreen,
    Color? orange,
    Color? blue,
    Color? border,
  }) {
    return FarmPalette(
      cream: cream ?? this.cream,
      green: green ?? this.green,
      dark: dark ?? this.dark,
      muted: muted ?? this.muted,
      paleGreen: paleGreen ?? this.paleGreen,
      orange: orange ?? this.orange,
      blue: blue ?? this.blue,
      border: border ?? this.border,
    );
  }

  @override
  FarmPalette lerp(ThemeExtension<FarmPalette>? other, double t) {
    if (other is! FarmPalette) return this;
    return FarmPalette(
      cream: Color.lerp(cream, other.cream, t)!,
      green: Color.lerp(green, other.green, t)!,
      dark: Color.lerp(dark, other.dark, t)!,
      muted: Color.lerp(muted, other.muted, t)!,
      paleGreen: Color.lerp(paleGreen, other.paleGreen, t)!,
      orange: Color.lerp(orange, other.orange, t)!,
      blue: Color.lerp(blue, other.blue, t)!,
      border: Color.lerp(border, other.border, t)!,
    );
  }
}

extension FarmPaletteContext on BuildContext {
  FarmPalette get farmPalette => Theme.of(this).extension<FarmPalette>()!;
}
